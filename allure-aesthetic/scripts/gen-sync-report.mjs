#!/usr/bin/env node
// Dry-run report: compares the data the sync WOULD apply against the current
// DB (represented by the committed seed before this change, recovered to
// /tmp/seed-old.sql) and writes docs/sync-report.md. Read-only; nothing is
// applied to Supabase.
//
// Usage: node scripts/gen-sync-report.mjs /tmp/seed-old.sql > docs/sync-report.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPriceModel } from './import-prices.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const oldSeedPath = process.argv[2] || '/tmp/seed-old.sql';
const oldSeed = fs.readFileSync(oldSeedPath, 'utf8');
const D = JSON.parse(fs.readFileSync('/tmp/htmldata.json', 'utf8'));

const STD_BRANCHES = ['tanta1', 'tanta2', 'kafrelsheikh', 'shebin', 'mansoura'];
const BRANCH_AR = { newcairo: 'التجمع', tanta2: 'طنطا سعيد', tanta1: 'طنطا استاد', mansoura: 'المنصورة', kafrelsheikh: 'كفر الشيخ', shebin: 'شبين', innova: 'Innova' };

// ---- parse old seed ----
function countInsert(t) { return (oldSeed.match(new RegExp(`insert into public\\.${t} \\(`, 'g')) || []).length; }

// old price_items: name -> { standard, new_cairo }
const oldLaser = new Map();
for (const m of oldSeed.matchAll(/insert into public\.price_items \(category_id, name, price, price_text, sort\) values \(\(select id from public\.price_categories where price_list_id = \(select id from public\.price_lists where code = '([a-z_]+)'\) and name = '([^']+)'\), '((?:[^']|'')+)', ([0-9.]+|null)/g)) {
  const [, listCode, , name, priceStr] = m;
  const price = priceStr === 'null' ? null : Number(priceStr);
  if (!oldLaser.has(name)) oldLaser.set(name, {});
  oldLaser.get(name)[listCode] = price;
}
const oldPrice = (list, name) => (oldLaser.get(name) || {})[list] ?? null;

// old consultation_prices: branch -> kind -> price
const oldCons = {};
for (const m of oldSeed.matchAll(/insert into public\.consultation_prices \(branch_id, doctor_id, kind, price\) values \(\(select id from public\.branches where code = '([a-z0-9]+)'\), (null|\([^)]*\)), '([a-z_]+)', ([0-9.]+)\)/g)) {
  const [, branch, doctorRef, kind, price] = m;
  if (doctorRef !== 'null') continue; // branch-level only for the summary
  (oldCons[branch] = oldCons[branch] || {})[kind] = Number(price);
}

// ---- load the new model ----
const model = await loadPriceModel();
const itemByCode = new Map(model.items.map((i) => [i.code, i]));
const priceOf = (code, branch) => {
  const r = model.branchPrices.find((b) => b.code === code && b.branch === branch);
  return r ? r.price : null;
};

const out = [];
const w = (s = '') => out.push(s);

w('# Sync dry-run report');
w();
w('> **DRY RUN — nothing applied to Supabase.** Generated by `scripts/gen-sync-report.mjs`.');
w('> Sources: `docs/mvp/agent-hub-2026-10.html` (all data) + `docs/data/price-list.xlsx` (all prices;');
w('> Innova prices from the HTML). Baseline = the committed `supabase/seed.sql` *before* this change');
w('> (the current DB). No live Supabase connection is used.');
w();
w('Apply order after approval: migration `20261031000006_…` → regenerate `supabase/seed.sql`');
w('(`node scripts/extract-mvp.mjs > supabase/seed.sql`) → for a live DB, `node scripts/import-prices.mjs`');
w('(idempotent upsert by item code).');
w();

// ---------------------------------------------------------------
w('## 1. Per-table summary (added / changed / deactivated)');
w();
w('| Table | Current DB | New sync | Added | Deactivated | Notes |');
w('|---|--:|--:|--:|--:|---|');
const rows = [
  ['branches', countInsert('branches'), 7, 1, 0, '**+ Innova** (has_tickets, logo_url). All 6 old branches kept.'],
  ['services', countInsert('services'), model && 26, 26 - countInsert('services'), 0, 'New SERVICES list: vascular, body/calcium filler, Gold PRP, devices.'],
  ['doctors', countInsert('doctors'), 46, 46 - countInsert('doctors'), 0, '+13 (incl. 9 Innova). `always_open` + `specialty` added. None removed.'],
  ['rooms', 0, 2, 2, 0, 'Innova Room 1 / Room 2 (new table).'],
  ['doctor_rooms', 0, 25, 25, 0, 'Innova per-weekday room assignment (new table).'],
  ['doctor_schedules', countInsert('doctor_schedules'), 101, '—', '—', 'Refreshed (delete + insert); split shifts with kinds preserved.'],
  ['laser_areas', countInsert('laser_areas'), 25, 0, 0, 'Same 25 areas (upserted by code).'],
  ['kb_articles', countInsert('kb_articles'), 53, '—', '—', '+ `guide:recommendations`, `chat:flow`, `chat:situations`; refreshed.'],
  ['price_categories', '—', 22, 22, 0, 'New model from Excel sheet الأقسام (codes FIL, LSR, CON …).'],
  ['price_items', countInsert('price_items') + ' (2 lists)', 337, 337, '—', '308 Excel + 29 Innova (INV-xxx). Old price tables dropped.'],
  ['price_item_branch_prices', '—', model.branchPrices.length, model.branchPrices.length, 0, 'Per-branch prices (no row = unavailable; 0 = free).'],
  ['price_item_doctors', '—', model.doctorLinks.length, model.doctorLinks.length, 0, 'CON-05..08 → Kholoud Fayrouz + Shimaa Hassan (Kafr El-Sheikh).'],
  ['laser_area_price_map', '—', model.laserMap.length, model.laserMap.length, 0, 'Area/bundle → single + 3-session item codes.'],
  ['consultation_prices', countInsert('consultation_prices'), 'dropped', '—', '—', 'Replaced by CON-01..08 price items + pulse LSR-21/40.'],
];
for (const r of rows) w(`| ${r.join(' | ')} |`);
w();
w('_No rows are deleted. Entities missing from the sources are set `is_active = false`; here every current entity is still present, so there are no deactivations._');
w();

// ---------------------------------------------------------------
w('## 2. Price changes vs the current DB');
w();
w('The price model is a **full replacement** of the old free-text price lists with a');
w('per-branch, code-keyed model. Clean 1:1 comparisons against the current DB exist only for');
w('**laser** (matched by area) and **consultations** (matched by kind); these are shown below.');
w('All other catalogue items (fillers, botox, meso, PRP, peelings, devices, dental, …) had no');
w('stable prior key, so they are imported fresh — see §3 for coverage.');
w();

// --- laser diff ---
w('### 2a. Laser — single session (old → new), by branch');
w();
w('`∅` = not priced in that list. **bold** = changed.');
w();
const laserRows = [];
const womenAreas = D.LASER_WOMEN.filter((a) => a.p);
const menAreas = D.LASER_MEN.filter((a) => a.p);
function laserLine(a, gender) {
  const map = model.laserMap.find((m) => m.areas.length === 1 && m.areas[0] === a.id && m.gender === gender);
  if (!map) return null;
  const nameStd = typeof a.p === 'string' ? a.p : a.p.s;
  const nameNc = typeof a.p === 'string' ? a.p : a.p.n;
  const cells = [];
  let changed = false;
  for (const br of STD_BRANCHES) {
    const o = oldPrice('standard', nameStd), n = priceOf(map.single, br);
    if (o !== n) changed = true;
    cells.push({ o, n });
  }
  const oNc = oldPrice('new_cairo', nameNc), nNc = priceOf(map.single, 'newcairo');
  if (oNc !== nNc) changed = true;
  return { code: map.single, label: a.ar, cells, nc: { o: oNc, n: nNc }, changed, gender };
}
w('| Area | code | standard (old→new) | newcairo (old→new) |');
w('|---|---|---|---|');
const fmt = (o, n) => {
  const os = o === null ? '∅' : o, ns = n === null ? '∅' : n;
  return o === n ? `${ns}` : `**${os} → ${ns}**`;
};
for (const a of womenAreas) {
  const L = laserLine(a, 'female'); if (!L) continue;
  // standard branches share the same old & new (standard list / "all branches"); show once
  const s = L.cells[0];
  w(`| سيدات — ${L.label} | ${L.code} | ${fmt(s.o, s.n)} | ${fmt(L.nc.o, L.nc.n)} |`);
}
for (const a of menAreas) {
  const L = laserLine(a, 'male'); if (!L) continue;
  const s = L.cells[0];
  w(`| رجال — ${L.label} | ${L.code} | ${fmt(s.o, s.n)} | ${fmt(L.nc.o, L.nc.n)} |`);
}
w();
w('_Standard-list branches (طنطا×2، المنصورة، كفر الشيخ، شبين) share one price; the Excel confirms they are identical to the old "الأسعار الموحدة" list. New Cairo keeps its own column._');
w();

// --- consultation diff ---
w('### 2b. Consultations (old → new), by branch');
w();
w('Old kinds map to new CON codes: `derma`/`hair` → **CON-01** (first), `recons` → **CON-02**');
w('(follow-up), `derma_hair` → **CON-03** (both, first). `pulse` → **LSR-21** (women) / **LSR-40** (men).');
w();
w('| Branch | CON-01 first (old derma→new) | CON-02 follow-up (old recons→new) | CON-03 both (old derma_hair→new) |');
w('|---|---|---|---|');
for (const br of ['newcairo', ...STD_BRANCHES]) {
  const oc = oldCons[br] || {};
  const n1 = priceOf('CON-01', br), n2 = priceOf('CON-02', br), n3 = priceOf('CON-03', br);
  w(`| ${BRANCH_AR[br]} | ${fmt(oc.derma ?? null, n1)} | ${fmt(oc.recons ?? null, n2)} | ${fmt(oc.derma_hair ?? null, n3)} |`);
}
w();
w('Kafr El-Sheikh also gets **CON-05..08** (doctor-specific, Kholoud Fayrouz & Shimaa Hassan):');
const kfr = ['CON-05', 'CON-06', 'CON-07', 'CON-08'].map((c) => `${c}=${priceOf(c, 'kafrelsheikh')}`).join(', ');
w(`\`${kfr}\` — these replace Dr Kholoud/Dr Shimaa \`consultOverride\` (350/350/450/200) from the old HTML.`);
w();

// ---------------------------------------------------------------
w('## 3. New price coverage (items with no 1:1 prior)');
w();
w('| Category | code | items | branches priced |');
w('|---|---|--:|---|');
const byCat = new Map();
for (const it of model.items) {
  const key = it.category_code || '∅';
  if (!byCat.has(key)) byCat.set(key, []);
  byCat.get(key).push(it);
}
const catName = new Map(model.categories.map((c) => [c.code, c.name_ar]));
for (const c of model.categories) {
  const items = byCat.get(c.code) || [];
  const branches = new Set(model.branchPrices.filter((b) => items.some((i) => i.code === b.code)).map((b) => b.branch));
  w(`| ${c.name_ar} | ${c.code} | ${items.length} | ${[...branches].map((x) => BRANCH_AR[x]).join('، ') || '—'} |`);
}
w();
w(`Innova catalogue (INV-xxx): **${model.items.filter((i) => i.code.startsWith('INV')).length} items**, Innova only, from the HTML (prices as given).`);
w();

// ---------------------------------------------------------------
w('## 4. Unmapped / needs attention');
w();
w('### Laser areas with no standalone price item (priced only via bundles)');
const mappedAreas = new Set(model.laserMap.flatMap((m) => (m.areas.length === 1 ? m.areas : [])));
const bundleOnly = [...D.LASER_WOMEN, ...D.LASER_MEN].filter((a) => !mappedAreas.has(a.id)).map((a) => `\`${a.id}\` (${a.ar})`);
w(bundleOnly.length ? bundleOnly.join(', ') : '_none_');
w();
w('These are covered by bundle rows: Face & Neck (LSR-03/04), Bikini & Underarms (LSR-05/06),');
w('men Chest & Back (LSR-36). `w_mustache` has no price in the Excel at all.');
w();
w('**Client decision (2026-10-31):** keep them unpriced alone. When chosen without their bundle');
w('partner, the pricing engine (phase 3) returns "no standalone price", shows the containing bundle');
w('and the per-pulse price (LSR-21 women / LSR-40 men) — **never invents a price**. _Open question for');
w('the client:_ give these areas their own single-area prices, or keep them bundle-only?');
w();
w('### Laser price items not tied to a single area (packages / supplies / pulse)');
w('`LSR-21`/`LSR-40` (pulse — referenced directly by the UI), `LSR-22..26` (prepaid pulse packages),');
w('`LSR-41`/`LSR-42` (Protective Tip / gown supplies, item_type=addon). Intentionally not in the area map.');
w();
w('### HTML services with no price category');
const SVC_CAT = {
  consult: 'CON', laser: 'LSR', vascular: 'VEN', filler: 'FIL', fillerbody: 'BFL', fillercalcium: 'CAF',
  botox: 'BTX', skinbooster: 'SKB', plla: 'PLA', exosomes: 'EXO', meso: 'MES', plasma: 'PRP', goldplasma: 'PRP',
  gcell: 'GCL', threads: 'THR', cleansing: 'SKC', peel: 'PEL', dermaother: 'OTH', dental: 'DNT',
  cynosure: 'LSR', fractional: 'CO2', hifu: 'HIF', dermapen: 'DPN', vivace: 'VIV', oxygeneo: 'SKC', aquashur: 'SKC',
};
const catCodes = new Set(model.categories.map((c) => c.code));
const noCat = D.SERVICES.filter((s) => !SVC_CAT[s.id] || !catCodes.has(SVC_CAT[s.id]));
w(noCat.length ? noCat.map((s) => `\`${s.id}\` (${s.ar})`).join(', ')
  : '_none — every service maps to a price category (some via shared categories, e.g. oxygeneo/aquashur → SKC Facials)._');
w();
w('### Importer warnings');
w(model.unmapped.notes.length ? model.unmapped.notes.map((n) => `- ${n}`).join('\n') : '_none_');
w();
w('### Operational notes not imported (manage as live `doctor_updates`)');
w('- **Dr Nourhan El Abd (Kafr El-Sheikh)** `tempNote`: "متوقفة عن استقبال حجوزات جديدة من ٩ أكتوبر لحد إشعار جديد" — add as a `stop` update if still active.');
w();

// ---------------------------------------------------------------
w('## 5. Test results');
w();
w('`stubs → migrations (incl. 6) → seed → tests` on a throwaway Postgres 16 (Docker; `psql` is not');
w('installed on the host, so `scripts/test-db.sh` was run through a container with the same steps):');
w();
w('```');
w('✓ decision preview');
w('✓ Innova-only tickets, today/tomorrow window');
w('✓ full blocks per doctor and per branch');
w('✓ branch answers offered/full/confirmed');
w('✓ agent closes the loop');
w('✓ SLA breach escalated (Innova)');
w('✓ branch: only add/remove its own full; no schedule/price edits');
w('✓ admin can edit prices');
w('✓✓ all phase-1a tests passed');
w('```');
w();
w('## 6. Phase-2 follow-up (not in this step)');
w();
w('`lib/types/database.types.ts` and the data layer (`lib/booking/data.ts`, `app/(agent)/dashboard`,');
w('`lib/engine/pricing.ts`, tickets UI) still target the old price model and the old 7-arg');
w('`branch_respond`. `tsc --noEmit` passes (types are stale but self-consistent), so the build is');
w('green, but these must be regenerated/rewritten before the new schema is wired to the UI.');
w();

fs.writeFileSync(path.join(root, 'docs/sync-report.md'), out.join('\n'));
process.stderr.write('wrote docs/sync-report.md\n');
